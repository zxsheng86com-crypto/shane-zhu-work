import assert from 'node:assert/strict';
const { chromium, webkit } = await import(process.argv[2] || 'playwright');
const browser = await (process.argv.includes('--webkit') ? webkit.launch({ headless: true }) : chromium.launch({ channel: 'chrome', headless: true }));
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await page.goto('http://localhost:3000/work/dji-romo');
  const toggle = page.locator('.nav-toggle');
  const nav = page.locator('#main-navigation');
  assert.equal(await nav.isVisible(), false);
  assert.equal(await page.locator('.nav-clock').isVisible(), false);
  await toggle.click();
  assert.equal(await nav.isVisible(), true);
  assert.equal(await page.locator('.nav-mobile').evaluate(e => e.open), true);
  assert.equal(await page.locator('.wordmark').evaluate(e => getComputedStyle(e).color), 'rgb(255, 255, 255)');
  const typography = await page.locator('.case-text h2').first().evaluate(e => {
    const s = getComputedStyle(e);
    return { size: s.fontSize, weight: s.fontWeight, line: s.lineHeight, color: s.color };
  });
  assert.deepEqual(typography, { size: '20px', weight: '500', line: '22px', color: 'rgb(255, 255, 255)' });
  assert.deepEqual(await page.locator('header.nav').evaluate(e => ({ bg: getComputedStyle(e).backgroundColor, border: getComputedStyle(e).borderTopWidth })), { bg: 'rgb(0, 0, 0)', border: '0px' });
  await page.keyboard.press('Escape');
  assert.equal(await nav.isVisible(), false);
  assert.equal(await toggle.evaluate(e => e === document.activeElement), true);
  await toggle.click();
  await page.mouse.click(200, 400);
  assert.equal(await nav.isVisible(), false);
  await toggle.tap();
  await page.evaluate(() => window.scrollTo(0, 500));
  await page.waitForFunction(() => document.querySelector('header.nav').getBoundingClientRect().bottom <= 0);
  assert.equal(await nav.isVisible(), false, 'Scrolling down closes the expanded menu');
  await page.evaluate(() => { window.scrollTo(0, 496); window.dispatchEvent(new Event('scroll')); });
  await page.waitForTimeout(700);
  assert.equal(await page.locator('header.nav').evaluate(e => e.getBoundingClientRect().bottom <= 0), true, 'Tiny reverse movements do not flash the header');
  await page.waitForTimeout(1000);
  assert.equal(await page.evaluate(() => window.scrollY), 496, 'Idle scrolling position stays unchanged');
  await page.evaluate(() => window.scrollTo(0, 250));
  await page.waitForFunction(() => document.querySelector('header.nav').getBoundingClientRect().top >= 0);
  const readCopy = () => page.locator('.case-hero h1,.case-text>p').evaluateAll(es => es.map(e => ({color: getComputedStyle(e).color, size: e.matches('.case-text>p') ? getComputedStyle(e).fontSize : 'responsive'})));
  const mobileCopy = await readCopy();
  await page.setViewportSize({ width: 1440, height: 900 });
  assert.deepEqual(await readCopy(), mobileCopy, 'Copy colors and chapter body sizes match on both viewports');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await toggle.click();
  await nav.getByRole('link', { name: 'About' }).click();
  await page.waitForURL('**/about');
  assert.equal(await nav.isVisible(), false);
  await toggle.click();
  await page.screenshot({ path: '/tmp/mobile-navigation-open.png' });
  await page.setViewportSize({ width: 1440, height: 900 });
  assert.equal(await toggle.isVisible(), false);
  assert.equal(await page.locator('.nav-desktop').isVisible(), true);
  assert.equal(await page.locator('.nav-clock').isVisible(), true);
  const native = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, javaScriptEnabled: false });
  await native.goto('http://localhost:3000/work/dji-romo');
  await native.locator('.nav-toggle').tap();
  assert.equal(await native.locator('#main-navigation').isVisible(), true, 'Touch opens menu even before hydration');
  await native.locator('.nav-toggle').tap();
  assert.equal(await native.locator('#main-navigation').isVisible(), false);
  console.log('PASS: native touch, menu interactions, scroll hide/show after touch, black borderless surface, matching copy colors/sizes, desktop navigation');
} finally {
  await browser.close();
}
